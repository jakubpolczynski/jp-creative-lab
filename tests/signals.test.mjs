import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const url = new URL('../signals.js', import.meta.url);
let source;
try { source = await fs.readFile(url, 'utf8'); } catch { assert.fail('Missing deterministic signal animation module'); }
const {signalState,signalTiming,signalCycle,SIGNAL_SPEED} = await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const length=12;
const timing=signalTiming(length),cycle=signalCycle([length]);
const start=signalState(1,length), out=signalState(2,length), later=signalState(3,length);
assert.ok(start.outbound>=0 && start.outbound<.01,'Green starts at server');
assert.ok(out.outbound>start.outbound && later.outbound>out.outbound,'Green moves toward PC');
assert.equal(out.inbound,-100,'No unrelated blue impulse during green journey');
const back=signalState(timing.roomSend+.2,length), near=signalState(timing.serverArrival-.1,length);
assert.ok(back.inbound>near.inbound && near.inbound>=0,'Room reply returns toward server');
assert.equal(back.rackBlink,0,'No premature rack blink');
assert.ok(signalState(timing.serverArrival+.08,length).rackBlink>.5,'Receipt triggers rack blink');
assert.equal(signalState(timing.serverArrival+.8,length).rackBlink,0,'Rack returns to green');
assert.deepEqual(signalState(2+cycle,length),out,'Cycle repeats deterministically');
assert.equal(signalState(timing.roomArrival-.1,length).roomBlink,0,'Room must not react before green arrival');
assert.ok(signalState(timing.roomArrival+.1,length).roomBlink>.5,'Green arrival triggers room accents');
assert.equal(signalState(timing.roomSend-.1,length).roomBlink,0,'Room returns to its own color before reply');
assert.deepEqual(signalState(timing.serverArrival+.08,length,true),{outbound:-100,inbound:-100,rackBlink:0,roomBlink:0},'Reduced motion disables pulses/blink');
assert.equal(later.outbound-out.outbound,SIGNAL_SPEED,'Velocity is measured in world units, not path percentages');
console.log('PASS signal directions, physical velocity, causal arrival blink, repeat cycle, reduced motion');
