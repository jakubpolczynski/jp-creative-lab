import assert from 'node:assert/strict';
import {createSignalNetwork,SIGNAL_SPEED} from '../signals.js';
const paths=[{id:'a',length:10,color:[1,0,0]},{id:'b',length:20,color:[0,0,1]}];
const net=createSignalNetwork(paths);
let s=net.advance(2,{a:10,b:20});
assert.equal(s.links[0].outbound,SIGNAL_SPEED);
s=net.advance(2.5,{a:30,b:20});
assert.equal(s.links[0].outbound,7.5,'Extension cannot reset phase/progress');
assert.equal(s.links[1].outbound,7.5);
s=net.advance(3,{a:30,b:20});
assert.equal(s.links[0].roomBlink,0);
net.advance(3,{a:9,b:20});
s=net.advance(3.12,{a:9,b:20});
assert.ok(s.links[0].roomBlink>.5,'Shortening causes a real, single receipt at the changed endpoint');
assert.equal(s.links[0].outbound,-100);
s=net.advance(4.5,{a:9,b:20});
assert.ok(Math.abs(s.links[0].inbound-6.5)<1e-8,'Reply starts 1 s after receipt');
s=net.advance(4.5,{a:19,b:20});
assert.ok(Math.abs(s.links[0].inbound-16.5)<1e-8,'Reply retains distance travelled from its sender');
s=net.advance(8,{a:19,b:20});
assert.deepEqual(s.server.color,[1,0,0]);
assert.deepEqual(net.advance(8,{a:19,b:20},true).server.intensity,0);
const shortened=createSignalNetwork([{id:'x',length:30,color:[1,0,0]}]);
shortened.advance(2.5,{x:30});
assert.equal(shortened.advance(3,{x:9}).links[0].roomArrival,3,'A newly supplied shorter cable cannot cause receipt in the past');
assert.equal(shortened.advance(3.9,{x:9}).links[0].inbound,-100,'Reply waits a full second after actual update');
console.log('PASS dynamic signal speed, extension/shortening, single causal receipt and reply clock');
