import assert from 'node:assert/strict';
import {createCollisionWorld,boxCollider} from '../collisions.js';
import {createRope,stepRope,cableEndpoints} from '../cable-physics.js';
import {WORLD_ROOMS} from '../rooms.js';
for(const room of WORLD_ROOMS){
  const e=cableEndpoints(room,room.center,{lift:.2,scale:1},{lift:.1,scale:1});
  assert.equal(e.a[1],room.port[1]+.1);
  assert.equal(e.b[1],2.04);
}
const wall=boxCollider([0,1,0],[.12,2,2],'wall'),world=createCollisionWorld([wall]);
const ends={a:[-3,.8,0],b:[3,1.8,0],tangentA:[1,0,0],tangentB:[-1,0,0]};
const rope=createRope(ends,world);
for(let i=0;i<50;i++)stepRope(rope,1/60,ends,world,{reduced:false});
assert.deepEqual(rope.points[0],ends.a);assert.deepEqual(rope.points.at(-1),ends.b);
assert.ok(rope.points.flat().every(Number.isFinite));
for(let i=1;i<rope.points.length;i++)assert.equal(world.segmentHit(rope.points[i-1],rope.points[i],.085),null,'Entire capsule avoids the wall');
const before=rope.length,moved={...ends,b:[30,1.8,0]};
stepRope(rope,1/30,moved,world,{reduced:false});
assert.ok(rope.length>before+15,'Material extends without restricting endpoint');
assert.deepEqual(rope.points.at(-1),moved.b);
assert.ok(rope.points.every(p=>p[1]>=-.515-1e-8),'Invisible support plane');
const extended=rope.length;
stepRope(rope,1/30,ends,world,{reduced:false});
assert.ok(rope.length<extended-10,'Feeding back does not keep all historic cable material');
const collars=createCollisionWorld([boxCollider([-2.75,.8,0],[.02,.4,.4],'foreign-a'),boxCollider([2.75,1.8,0],[.02,.4,.4],'foreign-b')]);
const collarRope=createRope(ends,collars);
assert.equal(collars.segmentHit(collarRope.points[0],collarRope.points[1],.085),null,'Unrelated A-side obstruction is not exempt');
assert.equal(collars.segmentHit(collarRope.points.at(-2),collarRope.points.at(-1),.085),null,'Unrelated B-side obstruction is not exempt');
assert.ok(Math.hypot(...collarRope.points[1].map((v,j)=>v-ends.a[j]))<.2,'Collar shortens before a foreign obstruction; tangent and port stay attached');
const crossingEnds={a:[-3,1,0],b:[3,1,0],tangentA:[1,0,0],tangentB:[-1,0,0]};
const movingWorld=createCollisionWorld([]),sweptRope=createRope(crossingEnds,movingWorld);
const oldWall=boxCollider([0,1,-1],[.2,2,.1],'moving-wall');
movingWorld.set([{...boxCollider([0,1,1],[.2,2,.1],'moving-wall'),previous:oldWall}]);
stepRope(sweptRope,0,crossingEnds,movingWorld,{reduced:true});
assert.ok(sweptRope.points.some(p=>p[2]>1.13),'Mid-segment sweep must displace actual material ahead, not merely report a hit');
const staticWorld=createCollisionWorld([boxCollider([0,1,0],[.2,2,.1],'static-wall')]);
const inverse=staticWorld.sweptSegment([-2,1,-1],[2,1,-1],[-2,1,1],[2,1,1],.085);
assert.ok(inverse,'A moving segment also collides with static furniture');
const previous=[-2+4*inverse.along,1,-1],current=[-2+4*inverse.along,1,1];
assert.ok(staticWorld.project(current,previous,.085)[2]<-.13,'Inverse-motion response stays in front of the stationary barrier');
console.log('PASS pinned endpoints, full-segment solid collision, unlimited extension and gravity support');
